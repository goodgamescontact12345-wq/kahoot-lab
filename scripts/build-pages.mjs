#!/usr/bin/env node
/**
 * Build the static (GitHub Pages) edition of the kahoot·lab console.
 *
 * The hosted build is the exact UI shipped with `kahoot-lab serve`
 * (index.html / app.css / app.js are copied unchanged) plus the in-browser
 * demo backend (demo-engine.js + demo-boot.js + generated demo-fixtures.js),
 * because a static host cannot run the Node server and browsers cannot call
 * Kahoot's API cross-origin.
 *
 * Output: site/  (uploaded as the Pages artifact by .github/workflows/pages.yml)
 */

import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const UI = path.join(ROOT, "src", "web", "ui");
const FIXTURES = path.join(ROOT, "fixtures");
// `--out <dir>` lets the test-suite build into a temp dir
const outFlag = process.argv.indexOf("--out");
const OUT = outFlag !== -1 && process.argv[outFlag + 1]
  ? path.resolve(process.argv[outFlag + 1])
  : path.join(ROOT, "site");

async function build() {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  /* 1. index.html — absolute paths → relative (Pages serves under /<repo>/),
   *    inject the demo backend before app.js, neutralize the /api link. */
  let html = await readFile(path.join(UI, "index.html"), "utf8");
  const before = html;
  html = html
    .replace('href="/app.css"', 'href="app.css"')
    .replace('href="/api/health"', 'href="#" title="demo build: no live API"')
    .replace(
      '<script src="/app.js"></script>',
      [
        '<script>window.__KAHOOT_LAB_DEMO__ = true;</script>',
        '  <script src="demo-fixtures.js"></script>',
        '  <script src="demo-engine.js"></script>',
        '  <script src="demo-boot.js"></script>',
        '  <script src="app.js"></script>',
      ].join("\n  ")
    );
  if (html === before || !html.includes("demo-engine.js")) {
    throw new Error("index.html rewrite failed — its app.css/app.js markers changed?");
  }
  await writeFile(path.join(OUT, "index.html"), html);

  /* 2. UI assets, byte-identical to the ones the local server serves. */
  for (const file of ["app.css", "app.js", "demo-engine.js", "demo-boot.js"]) {
    await writeFile(path.join(OUT, file), await readFile(path.join(UI, file)));
  }

  /* 3. Generated fixture bundle for the demo engine. */
  const names = (await readdir(FIXTURES)).filter((f) => f.endsWith(".json")).sort();
  const map = {};
  for (const name of names) {
    map[name] = JSON.parse(await readFile(path.join(FIXTURES, name), "utf8"));
  }
  await writeFile(
    path.join(OUT, "demo-fixtures.js"),
    `/* generated by scripts/build-pages.mjs — do not edit */\n` +
      `window.__DEMO_FIXTURES__ = ${JSON.stringify(map, null, 2)};\n`
  );

  /* 4. Disable Jekyll processing on Pages. */
  await writeFile(path.join(OUT, ".nojekyll"), "");

  console.log(`built static console -> ${path.relative(ROOT, OUT) || OUT} (${names.length} fixture(s): ${names.join(", ")})`);
}

build().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
